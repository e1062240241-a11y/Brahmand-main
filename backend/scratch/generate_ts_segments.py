segments = []
current_time = 0.0
music_symbols = ["🎵", "🎶", "✨", "🎵"]

for idx, (line, start, end) in enumerate(lyrics_data):
    # Insert music segment if there is a gap of >= 1.0 second
    if start - current_time >= 1.0:
        duration = start - current_time
        num_symbols = max(4, int(duration))
        symbols_list = []
        for i in range(num_symbols):
            symbols_list.append(music_symbols[i % len(music_symbols)])
        segments.append({
            "type": "music",
            "startTime": round(current_time, 2),
            "endTime": round(start, 2),
            "items": symbols_list
        })

    # Split line into words
    words = line.split(" ")
    segments.append({
        "type": "vocal",
        "startTime": round(start, 2),
        "endTime": round(end, 2),
        "items": words
    })

    current_time = end

# Add final music/outro block
if current_time < 961.39:
    duration = 961.39 - current_time
    num_symbols = max(4, int(duration))
    symbols_list = []
    for i in range(num_symbols):
        symbols_list.append(music_symbols[i % len(music_symbols)])
    segments.append({
        "type": "music",
        "startTime": round(current_time, 2),
        "endTime": 961.39,
        "items": symbols_list
    })

# Format as typescript array content
ts_content = "const HANUMAN_CHALISA_SEGMENTS = [\n"
for i, seg in enumerate(segments):
    items_str = ", ".join([f"'{item}'" for item in seg["items"]])
    ts_content += f"  {{ type: '{seg['type']}', startTime: {seg['startTime']}, endTime: {seg['endTime']}, items: [{items_str}] }}"
    if i < len(segments) - 1:
        ts_content += ",\n"
    else:
        ts_content += "\n"
ts_content += "];\n"

output_path = "c:/Users/prarh/Desktop/Brahmand-main/backend/scratch/ts_segments.txt"
with open(output_path, "w", encoding="utf-8") as f:
    f.write(ts_content)

print(f"TS segments written to: {output_path}")
print(f"Total segments: {len(segments)}")
vocal_count = sum(1 for s in segments if s['type'] == 'vocal')
