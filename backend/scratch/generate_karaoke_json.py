structure = []
current_time = 0.0

for idx, (line, start, end) in enumerate(lyrics_data):
    # Insert music segment if there is a gap of >= 1.0 second
    if start - current_time >= 1.0:
        symbols = ["♪", "♫", "✨"]
        if current_time == 0.0:
            symbols = ["♪", "♫", "ॐ", "✨", "🙏"]
        structure.append({
            "type": "music",
            "start": float(round(current_time, 2)),
            "end": float(round(start, 2)),
            "symbols": symbols
        })

    # Process lyric line
    words = line.split(" ")
    num_words = len(words)
    duration = end - start
    word_duration = duration / num_words

    words_list = []
    for w_idx, w in enumerate(words):
        w_start = start + w_idx * word_duration
        w_end = w_start + word_duration
        words_list.append({
            "word": w,
            "start": float(round(w_start, 2)),
            "end": float(round(w_end, 2))
        })

    structure.append({
        "type": "lyric",
        "line": line,
        "words": words_list
    })

    current_time = end

# Add final music/outro block
if current_time < 961.39:
    structure.append({
        "type": "music",
        "start": float(round(current_time, 2)),
        "end": 961.39,
        "symbols": ["♪", "♫", "ॐ", "✨", "🙏"]
    })

