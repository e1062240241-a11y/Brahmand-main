DEVANAGARI_DIGITS = str.maketrans("0123456789", "०१२३४५६७८९")

def to_dev(n: int) -> str:
    return str(n).translate(DEVANAGARI_DIGITS)

def format_range(ch: int, start: int, end: int) -> str:
    if start == end:
        return f"{to_dev(ch)}.{to_dev(start)}"
    return f"{to_dev(ch)}.{to_dev(start)} - {to_dev(ch)}.{to_dev(end)}"

def load_raw_chapter(ch: int) -> dict:
    file_path = RAW_DATA_DIR / f"bhagavad_gita_chapter_{ch}.json"
    with open(file_path, "r", encoding="utf-8") as f:
        data = json.load(f)
    verses_by_num = {}
    for row in data.get("BhagavadGitaChapter", []):
        v_num = row.get("verse")
        if v_num:
            verses_by_num[int(v_num)] = row
    return verses_by_num

def get_clean_sanskrit(row: dict) -> str:
    t = row.get("text", "").strip()
    return t

def get_best_hindi(row: dict) -> str:
    translations = row.get("translations", {})
    for key in ["swami ramsukhdas", "swami tejomayananda", "sri harikrishnadas goenka", "hindi"]:
        val = translations.get(key)
        if isinstance(val, str) and val.strip() and "did not comment" not in val.lower():
            # Clean leading markers
            cleaned = re.sub(r'^(?:।।\s*\d+(?:\.\d+)?\s*।।|\d+\.\d+(?:\s*-\s*\d+\.\d+)?\.?)\s*', '', val.strip())
            return cleaned.strip()
    return ""

