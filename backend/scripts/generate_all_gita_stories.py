def generate_chapter_story(ch: int) -> dict:
    spec = CHAPTER_SPECS[ch]
    raw_verses = load_raw_chapter(ch)
    
    scenes_output = []
    for sc in spec["scenes"]:
        seq = sc["seq"]
        start_v = sc["start"]
        end_v = sc["end"]
        scene_id = f"scene_{ch}_{seq}"
        display_range = format_range(ch, start_v, end_v)
        
        # Build dialogues
        dialogue_v_num = sc["dialogue_verse"]
        row = raw_verses.get(dialogue_v_num, {})
        sanskrit_text = get_clean_sanskrit(row)
        hindi_text = get_best_hindi(row)
        
        # Format verse ref
        v_ref = f"{to_dev(ch)}.{to_dev(dialogue_v_num)}"
        
        dialogues = [
            DialogueItem(
                speaker=sc["speaker"],
                speaker_display=sc["speaker_display"],
                dialogue_hindi=hindi_text or sc["sutra"],
                sanskrit_shloka=sanskrit_text,
                verse_ref=v_ref,
            )
        ]
        
        # Build transcript
        speaker_name = sc["speaker_display"]
        transcript = f"काल कहता है: {sc['narrative']} {speaker_name} ने कहा: {hindi_text or sc['sutra']}"
        
        chintan = ChintanBindu(
            sutra_title=sc["sutra"],
            vedantic_concept=sc["concept"],
            inner_reflection=sc["reflection"],
        )
        
        scene_obj = StoryScene(
            scene_id=scene_id,
            seq=seq,
            title_hi=sc["title_hi"],
            title_en=sc["title_en"],
            start_verse=start_v,
            end_verse=end_v,
            display_range=display_range,
            narrative_hindi=sc["narrative"],
            dialogues=dialogues,
            chintan_bindu=chintan,
            deeper_study_ref=f"/library/bhagavad-gita-3d?chapter={ch}&verse={start_v}",
            transcript=transcript,
            duration_seconds_est=60,
        )
        scenes_output.append(scene_obj)
        
    chapter_obj = GitaStoryChapter(
        chapter=ch,
        title_sanskrit=spec["title_sanskrit"],
        title_hindi=spec["title_hindi"],
        title_english=spec["title_english"],
        total_verses=spec["total_verses"],
        theological_framing_disclaimer=(
            "यह कथा-प्रवाह, काल-चेतना के सूत्रात्मक परिप्रेक्ष्य से कही गई एक नाट्यमयी व्याख्या है। "
            "मूल गीता के सनातन श्लोक एवं श्रीभगवान् के वचनों की दिव्यता अक्षुण्ण है; यहाँ 'समय' केवल "
            "इतिहास और दर्शन के साक्षी रूप में कथा-तंतु को जोड़ता है।"
        ),
        time_opening_monologue=spec["monologue"],
        review_status=ReviewStatus.SCHOLAR_REVIEW,
        scholar_reviewer="ब्रह्माण्ड सनातन शोध पीठ (Brahmand Vedic & Scriptural Research)",
        scenes=scenes_output,
    )
    
    return chapter_obj

def main():
    print("Beginning generation and validation for Gita Chapters 2 through 18...")
    success_count = 0
    for ch in range(2, 19):
        story = generate_chapter_story(ch)
        # Validate Pydantic model
        validated = GitaStoryChapter.model_validate(story.model_dump())
        json_data = validated.model_dump()
        
        # Write to backend
        backend_path = BACKEND_STORY_DIR / f"chapter_{ch}.json"
        with open(backend_path, "w", encoding="utf-8") as f:
            json.dump(json_data, f, ensure_ascii=False, indent=2)
            
        # Write to frontend
        frontend_path = FRONTEND_STORY_DIR / f"chapter_{ch}.json"
        with open(frontend_path, "w", encoding="utf-8") as f:
            json.dump(json_data, f, ensure_ascii=False, indent=2)
            
        print(f"✓ Chapter {ch} generated ({validated.title_sanskrit}, {len(validated.scenes)} scenes, {validated.total_verses} verses)")
        success_count += 1
        
    print(f"\nSuccessfully generated and validated {success_count} chapters in both backend and frontend!")

if __name__ == "__main__":
    main()
